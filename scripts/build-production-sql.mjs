#!/usr/bin/env node
// Writes supabase/production/all-in-one.sql: every migration in order + the production marker, for a NEW, empty
// production Supabase project (one paste in the SQL Editor). No seed, no demo data.
// `npm run sql:production` after adding a migration; a test fails if the file is out of date.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../supabase/migrations/", import.meta.url);
const files = readdirSync(dir).filter((name) => /^\d{4}_.*\.sql$/.test(name)).sort();

export function productionSql() {
  const parts = files.map((name) => `-- ===========================================================================\n-- ${name}\n-- ===========================================================================\n\n${readFileSync(new URL(name, dir), "utf8").trim()}\n`);
  return `-- Maati Living — PRODUCTION database setup (generated by scripts/build-production-sql.mjs; don't edit by hand).
-- Run ONCE on a NEW, EMPTY Supabase project: SQL Editor → New query → paste this whole file → Run.
-- Contains migrations ${files[0].slice(0, 4)}–${files.at(-1).slice(0, 4)} in order and marks the database as production
-- (which also blocks the demo seed). No sample products or demo data. For an existing database, run only the
-- migrations it doesn't have yet, one file at a time, from supabase/migrations/.

${parts.join("\n")}
-- ===========================================================================
-- Mark this database as production (checked by npm run check:launch; the demo seed refuses to run here)
-- ===========================================================================

insert into public.settings (key, value) values ('environment', '"production"')
on conflict (key) do update set value = excluded.value;
`;
}

if (process.argv[1]?.endsWith("build-production-sql.mjs")) {
  writeFileSync(new URL("../supabase/production/all-in-one.sql", import.meta.url), productionSql());
  console.log(`Wrote supabase/production/all-in-one.sql (${files.length} migrations).`);
}
